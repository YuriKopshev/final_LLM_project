"""Промпты (system + user) для каждого сценария."""

SYSTEM = (
    "Ты — ассистент контент-мейкера. Работаешь с текстом статьи или подкаста. "
    "Отвечай на русском, без вступлений и пояснений, строго в запрошенном формате."
)

USER_TEMPLATES = {
    "summary": (
        "Сделай короткий саммари-пост для Telegram (до 900 символов): "
        "1 строка-заголовок, затем 4-5 ключевых мыслей списком с символом «•».\n\n"
        "Текст:\n{text}"
    ),
    "headlines": (
        "Придумай ровно 5 цепляющих заголовков для этого материала, "
        "каждый на новой строке, нумерация 1-5. Затем строка «Цитаты:» и "
        "2 самые кликбейтные цитаты из текста, каждая на новой строке с символом «•».\n\n"
        "Текст:\n{text}"
    ),
    "faq": (
        "Составь FAQ по тексту: 5 вопросов, которые могут задать читатели, с краткими "
        "ответами. Формат: «В: ...» и «О: ...» на отдельных строках.\n\nТекст:\n{text}"
    ),
}


def build_prompt(scenario: str, text: str) -> tuple[str, str]:
    return SYSTEM, USER_TEMPLATES[scenario].format(text=text)
